#!/usr/bin/env python3
"""Generate the reference part of an agent's README.md from the files that control the agent.

    venv_workflows/bin/python scripts/agentkit/agent_readme.py <agent>            print the README
    venv_workflows/bin/python scripts/agentkit/agent_readme.py <agent> --check    exit 1 if it is out of date
    venv_workflows/bin/python scripts/agentkit/agent_readme.py <agent> --write    rewrite the generated part

The README lives at workflows/<workflow>/agents/<agent>/README.md. Its top part (purpose, place in the line)
is written by hand and kept. Everything between the BEGIN and END markers is generated from the definition's
frontmatter, settings.json, guard.json, env.allow, the base settings, tests/enforcers.json and tasks/, so it
cannot drift from what the launcher really uses: a test runs --check for every agentkit agent.

Nothing here runs a grader or reads a run folder; the output depends only on committed files.
"""
import argparse
import ast
import re
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parent
sys.path.insert(0, str(KIT))
import launch  # noqa: E402
from launch import agentlib, load_json  # noqa: E402

BEGIN = ("<!-- BEGIN GENERATED by scripts/agentkit/agent_readme.py from the files that control this agent. "
         "Do not edit by hand; run `venv_workflows/bin/python scripts/agentkit/agent_readme.py {name} --write`. -->")
END = "<!-- END GENERATED -->"
PY = "venv_workflows/bin/python"


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def key_check_doc(grader):
    """First paragraph of key_check's docstring, read without running the grader."""
    tree = ast.parse(grader.read_text())
    for node in tree.body:
        if isinstance(node, ast.FunctionDef) and node.name == "key_check":
            doc = ast.get_docstring(node) or ""
            text = re.sub(r"\s+", " ", doc).replace("Returns (ok, details).", "")
            text = re.sub(r"^The key's pedigree, with no LLM in it[.:]\s*", "", text).strip()
            return text or "(no docstring)"
        if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "key_check" for t in node.targets):
            return "reuses another task's key check (see grade.py)"
    return "**none: breaks the key rule**"


def yes(flag):
    return "yes" if flag else "no"


def generated(name):
    definition, folder, workflow = launch.find_agent(name)
    agent = agentlib.load_agent(definition)
    rel = agentlib.rel
    settings = load_json(folder / "settings.json")
    perms = settings.get("permissions", {})
    guard = load_json(folder / "guard.json")
    env = launch.env_names(folder)
    base = load_json(KIT / "base_settings.json")
    box = base["sandbox"]
    enforcers = load_json(folder / "tests" / "enforcers.json")["enforcers"]
    tasks = sorted(d for d in (folder / "tasks").iterdir() if (d / "task.json").is_file())
    first_task = tasks[0].name if tasks else "<task_id>"

    out = [BEGIN.format(name=name), "", "## At a glance", "",
           f"- **Definition:** `{rel(definition)}` (frontmatter and system prompt)",
           f"- **Workflow:** `{workflow}`",
           f"- **Model:** `{agent['model']}`; permission mode `{agent['permission_mode']}`; "
           f"at most {agent['max_turns']} turns",
           f"- **Runs:** `runs/{workflow}/{name}/<run_id>/`, one folder per call: `PROVENANCE.md`, "
           "`manifest.json`, `transcript.jsonl`, `answer.json`, `grade.json`, `guard.jsonl`, `workspace/`",
           "", "## How to launch it", "", "```bash",
           f"{PY} scripts/agentkit/launch.py {name} --task <task_id>             # one task",
           f"{PY} scripts/agentkit/launch.py {name} --task {first_task} --redteam   # the escape probes",
           f"{PY} -m unittest discover -s {rel(folder)}/tests   # this agent's tests",
           f"{PY} -m unittest discover -s scripts/agentkit/tests                  # the harness tests",
           "```", "",
           "Exit codes: 0 PASS, 1 FAIL, 3 ABSTAIN (the agent returned `blocked`), 4 ERROR, 5 refused before any "
           "call. A real call is refused while an enforcer is unbuilt, or when no red-team PASS matches the "
           "current barriers (any change to the harness, the settings, the tools or the Claude Code version "
           "needs a new `--redteam` run first).", "",
           "## Tools and permissions", "",
           f"- **Tools:** {', '.join(agent['tools']) or 'none'}",
           f"- **Disallowed tools:** {', '.join(agent['disallowed']) or 'none'}",
           f"- **Permission rules** (`settings.json`): allow {', '.join(f'`{r}`' for r in perms.get('allow', []))}"
           f"; deny {', '.join(f'`{r}`' for r in perms.get('deny', []))}",
           "- **Every tool call** passes `scripts/agentkit/guard.py` first: file paths must resolve inside the "
           "working folder, PROVENANCE.md is never writable, and a shell command must be one plain command "
           "matching the allowlist",
           f"- **Shell allowlist** (`guard.json`): {', '.join(f'`{p}`' for p in guard.get('bash_allow', []))}",
           f"- **Required outputs** (checked by `stop_check.py` before the agent may finish): "
           f"{', '.join(f'`{p}`' for p in guard.get('required_outputs', [])) or 'none'}",
           f"- **Environment** (`env.allow`): {', '.join(env)}; the launcher adds PATH, TMPDIR and its own "
           "AGENTKIT_* variables and drops everything else",
           "", "## Sandbox", "",
           "From `scripts/agentkit/base_settings.json`, the same for every agentkit agent; it covers the shell "
           "and every program started from it.", "",
           f"- **On:** {yes(box.get('enabled'))}; a missing sandbox stops the run: "
           f"{yes(box.get('failIfUnavailable'))}; unsandboxed commands allowed: "
           f"{yes(box.get('allowUnsandboxedCommands'))}",
           f"- **Network:** allowed domains: {', '.join(box['network']['allowedDomains']) or 'none'}",
           f"- **Reads denied:** {', '.join(f'`{p}`' for p in box['filesystem']['denyRead'])} "
           "(`{GITROOT}` is the whole repository)",
           f"- **Reads re-allowed:** {', '.join(f'`{p}`' for p in box['filesystem']['allowRead'])}",
           f"- **Secret variables removed:** {', '.join(e['name'] for e in box['credentials']['envVars'])}",
           "", "## Rules and their enforcers", "",
           "Each \"Never\" in the definition, with what enforces it outside the prompt (`tests/enforcers.json`; "
           "a test fails if a rule has no entry).", "",
           "| | Never | Layer | Status |", "|---|---|---|---|"]
    out += [f"| {e['id']} | {cell(e['rule'])} | {', '.join(e['layer'])} | {cell(e['status'])} |" for e in enforcers]
    out += ["", "## Tasks", "",
            "Each task folder holds `task.json` (the work order the agent sees; read it before a run) and "
            "`grade.py` (never shown to the agent). A probe task also has `expect.json`, the hidden expected "
            "outcome. Every grader proves its own key with no LLM in the loop (`key_check`).", "",
            "| Task | Goal | Kind | Key check |", "|---|---|---|---|"]
    for d in tasks:
        task = load_json(d / "task.json")
        expect = launch.load_expectation(d)
        kind = (f"probe: expected {expect['outcome']}" if expect else
                "blind derivation: checks with no key, then a comparison" if not task.get("given")
                else "known answer")
        out.append(f"| `{d.name}` | {task['goal']} | {kind} | {cell(key_check_doc(d / 'grade.py'))} |")
    files = sorted(rel(p) for p in folder.rglob("*")
                   if p.is_file() and "__pycache__" not in p.parts and p.name != "README.md")
    out += ["", "## Files", "", "This agent:", "", f"- `{rel(definition)}`"] + [f"- `{f}`" for f in files]
    out += ["", "The harness, shared by every agentkit agent:", "",
            "- `scripts/agentkit/launch.py`: the launcher (gates, settings, call, audit, grade, record)",
            "- `scripts/agentkit/guard.py`: the check before every tool call",
            "- `scripts/agentkit/stop_check.py`: the check before the agent may finish",
            "- `scripts/agentkit/provenance.py`: the hash-chained PROVENANCE.md",
            "- `scripts/agentkit/redteam_probes.py`: the escape probes",
            "- `scripts/agentkit/base_settings.json`: project-wide denies and the sandbox",
            "- `scripts/agentkit/agent_readme.py`: this file's generator",
            "- `scripts/agentlib.py`: loads definitions, checks schemas, builds the `claude` command",
            "", END]
    return "\n".join(out) + "\n"


def readme_path(name):
    _, folder, _ = launch.find_agent(name)
    return folder / "README.md"


def split(text):
    """(hand-written part, generated part) of an existing README."""
    i = text.find("<!-- BEGIN GENERATED")
    j = text.find(END)
    if i < 0 or j < 0:
        return text, ""
    return text[:i], text[i:j + len(END)] + "\n"


def compose(name):
    path = readme_path(name)
    hand = split(path.read_text())[0] if path.is_file() else f"# {name}\n\n(What this agent is for.)\n\n"
    return hand + generated(name)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("agent")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true")
    g.add_argument("--write", action="store_true")
    a = ap.parse_args(argv)
    path = readme_path(a.agent)
    text = compose(a.agent)
    if a.check:
        current = path.read_text() if path.is_file() else ""
        if current != text:
            print(f"{agentlib.rel(path)} is out of date: run {PY} scripts/agentkit/agent_readme.py "
                  f"{a.agent} --write", file=sys.stderr)
            return 1
        print(f"{agentlib.rel(path)} is up to date")
        return 0
    if a.write:
        path.write_text(text)
        print(f"wrote {agentlib.rel(path)}")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
