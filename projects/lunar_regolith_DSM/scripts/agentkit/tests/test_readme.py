"""Every agentkit agent has a README.md whose generated part matches the files that control the agent.

An agentkit agent is one with tests/enforcers.json in its folder. Its README's reference part (tools,
permissions, sandbox, rules, tasks, files) is generated by agent_readme.py; this test fails when someone changes
a controlling file and forgets to regenerate, so the README never says something the launcher does not do.
"""
import sys
import unittest
from pathlib import Path
from unittest import mock

KIT = Path(__file__).resolve().parents[1]
ROOT = KIT.parents[1]
sys.path.insert(0, str(KIT))
import agent_readme  # noqa: E402


def agentkit_agents():
    return sorted(p.parents[1].name for p in ROOT.glob("workflows/*/agents/*/tests/enforcers.json"))


class Readmes(unittest.TestCase):
    def test_every_agentkit_agent_has_a_current_readme(self):
        agents = agentkit_agents()
        self.assertIn("beth-mathematician", agents)
        for name in agents:
            path = agent_readme.readme_path(name)
            self.assertTrue(path.is_file(), f"{name}: no README.md; run agent_readme.py {name} --write")
            self.assertEqual(path.read_text(), agent_readme.compose(name),
                             f"{name}: README.md is out of date; run agent_readme.py {name} --write")

    def test_hand_written_part_is_kept_and_a_change_is_caught(self):
        name = "beth-mathematician"
        text = agent_readme.compose(name)
        hand, gen = agent_readme.split(text)
        self.assertIn("Its place in the line", hand)
        self.assertTrue(gen.startswith("<!-- BEGIN GENERATED") and gen.rstrip().endswith(agent_readme.END))
        real = agent_readme.generated
        with mock.patch.object(agent_readme, "generated", lambda n: real(n).replace("dontAsk", "default")):
            self.assertNotEqual(agent_readme.compose(name), text)
            self.assertEqual(agent_readme.split(agent_readme.compose(name))[0], hand)

    def test_every_task_is_listed_with_its_key_check(self):
        text = agent_readme.generated("beth-mathematician")
        _, folder, _ = agent_readme.launch.find_agent("beth-mathematician")
        for d in (folder / "tasks").iterdir():
            if (d / "task.json").is_file():
                self.assertIn(f"`{d.name}`", text)
        self.assertNotIn("breaks the key rule", text)


if __name__ == "__main__":
    unittest.main()
